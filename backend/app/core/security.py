from fastapi import Header, HTTPException, status
from app.core.config import settings

async def verify_session_token(x_session_token: str = Header(None, alias="X-Session-Token")):
    """
    Validates that incoming HTTP requests carry the dynamic one-time session token
    generated by the Tauri desktop process, preventing unauthorized local access.
    """
    if not settings.SESSION_TOKEN:
        # In dev mode without SESSION_TOKEN specified, allow request
        return
        
    if not x_session_token or x_session_token != settings.SESSION_TOKEN:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or missing session authentication token"
        )

